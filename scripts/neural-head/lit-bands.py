#!/usr/bin/env python3
"""Writes Shared/Neural/NeuralLitBands.swift: the rows of the 640 by 420 design the interior pass
has to draw. A row band is as wide as the lit pixels of the interior layer, the first two masks
and their blooms reach in it, plus a margin, so the mesh costs nothing where nothing is lit and
cuts nothing where something is. Run after pack.py whenever Resources/Neural/png changes."""
import sys
from pathlib import Path

import numpy as np
from PIL import Image

ROOT = Path(__file__).resolve().parents[2]
PNG = ROOT / "Resources/Neural/png"
OUT = ROOT / "Shared/Neural/NeuralLitBands.swift"
DW, DH = 640, 420
BAND = 6
MARGIN = 4


def load(name):
    return np.array(Image.open(PNG / f"{name}.png").convert("RGBA"))


def lit_mask(w=1536, h=1008):
    interior = load("interior")
    lit = interior[..., 3] > 0
    for name in ("mask0", "mask1"):
        lit |= (load(name)[..., :4] > 0).any(axis=2)
    for name in ("bloom0", "bloom1"):
        small = (load(name)[..., :4] > 0).any(axis=2)
        grown = np.pad(small, 1)
        dil = np.zeros_like(small)
        for dy in (0, 1, 2):
            for dx in (0, 1, 2):
                dil |= grown[dy : dy + small.shape[0], dx : dx + small.shape[1]]
        lit |= np.kron(dil, np.ones((h // small.shape[0], w // small.shape[1]), bool))
    return lit


def main():
    lit = lit_mask()
    h, w = lit.shape
    sx, sy = DW / w, DH / h
    ys, xs = np.nonzero(lit)
    bands = []
    y = 0
    while y < DH:
        y1 = min(DH, y + BAND)
        rows = (ys * sy >= y - MARGIN) & (ys * sy < y1 + MARGIN)
        if rows.any():
            x0 = max(0, int(np.floor(xs[rows].min() * sx)) - MARGIN)
            x1 = min(DW, int(np.ceil((xs[rows].max() + 1) * sx)) + MARGIN)
            bands.append((y, y1, x0, x1))
        y = y1
    covered = np.zeros_like(lit)
    for y0, y1, x0, x1 in bands:
        covered[int(y0 / sy) : int(y1 / sy), int(x0 / sx) : int(x1 / sx)] = True
    missing = int((lit & ~covered).sum())
    area = sum((b[1] - b[0]) * (b[3] - b[2]) for b in bands) / (DW * DH)
    lines = [
        "/// The rows of the 640 by 420 design the interior pass draws, as `y0, y1, x0, x1`: generated by",
        "/// `scripts/neural-head/lit-bands.py` from the packed layers, so regenerate it with the assets.",
        "enum NeuralLitBands {",
        "    static let rows: [(y0: Float, y1: Float, x0: Float, x1: Float)] = [",
    ]
    for y0, y1, x0, x1 in bands:
        lines.append(f"        ({y0}, {y1}, {x0}, {x1}),")
    lines += ["    ]", "}", ""]
    OUT.write_text("\n".join(lines))
    print(f"{len(bands)} bands, {area * 100:.1f}% of the design, {missing} lit pixels uncovered")
    return 1 if missing else 0


sys.exit(main())
